#!/usr/bin/env python3
"""Generate ``dippy-rs/src/sql/functions.rs``, the SQLGlot-derived function table.

The Rust SQL checker parses SQL with the ``sqlparser`` crate and cannot run
SQLGlot. It needs one fact that only SQLGlot knows:

* FUNCTIONS: function names with, per parser dialect, a bit mask of argument
  counts (0-4) for which ``is_readonly_sql`` returns True (with column
  arguments, or a string literal as the first or last one). Candidates are
  every function name a SQLGlot parser of the supported dialects knows, plus
  the DuckDB read-only functions Python accepts as anonymous calls.
* TYPES: type names with a bit per parser dialect for which a CAST verifies;
  the checker consults it for types ``sqlparser`` does not know.

Usage: sql_tables.py > rust/dippy-rs/src/sql/functions.rs
"""

from __future__ import annotations

import os
import sys
import tempfile
from multiprocessing import Pool
from pathlib import Path

os.environ["HOME"] = tempfile.mkdtemp(prefix="dippy-sql-home-")
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

import sqlglot  # noqa: E402

from dippy.core.sql import _DUCKDB_READONLY_FUNCTIONS, is_readonly_sql  # noqa: E402

# Parser dialects in the order of the Rust `Dialect` enum.
DIALECTS = [None, "postgres", "mysql", "sqlite", "tsql", "duckdb", "athena"]


def candidates() -> list[str]:
    names = set(_DUCKDB_READONLY_FUNCTIONS)
    for dialect in DIALECTS:
        parser = sqlglot.Dialect.get_or_raise(dialect).parser_class
        names.update(name.lower() for name in parser.FUNCTIONS)
        names.update(name.lower() for name in parser.FUNCTION_PARSERS)
        names.update(name.lower() for name in parser.NO_PAREN_FUNCTION_PARSERS)
    return sorted(name for name in names if name.isidentifier())


def ok(sql: str, dialect) -> bool:
    try:
        return is_readonly_sql(sql, dialect=dialect) is True
    except Exception:
        return False


def arg_lists(n: int) -> list[str]:
    """Columns, or a string literal first (a unit) or last (a separator)."""
    args = ["a", "b", "c", "d"][:n]
    variants = [args]
    if n:
        variants += [["'day'"] + args[1:], args[:-1] + ["','"]]
    return [", ".join(v) for v in variants]


def masks(name: str) -> tuple[str, list[int]]:
    result = []
    for dialect in DIALECTS:
        mask = 0
        for n in range(5):
            if any(
                ok(f"SELECT {name}({arg_list}) FROM t", dialect)
                and ok(f"SELECT {name.upper()}({arg_list}) FROM t", dialect)
                for arg_list in arg_lists(n)
            ):
                mask |= 1 << n
        result.append(mask)
    return name, result


def type_candidates() -> list[str]:
    names = {t.name for t in sqlglot.exp.DataType.Type}
    for dialect in DIALECTS:
        tokenizer = sqlglot.Dialect.get_or_raise(dialect).tokenizer_class
        names.update(key for key in tokenizer.KEYWORDS if key.isidentifier())
    return sorted(name.upper() for name in names)


def type_mask(name: str) -> tuple[str, int]:
    mask = 0
    for index, dialect in enumerate(DIALECTS):
        if ok(f"SELECT CAST(a AS {name}) FROM t", dialect) and ok(
            f"SELECT CAST(a AS {name.lower()}) FROM t", dialect
        ):
            mask |= 1 << index
    return name, mask


def main() -> None:
    with Pool() as pool:
        rows = [row for row in pool.map(masks, candidates()) if any(row[1])]
        types = [row for row in pool.map(type_mask, type_candidates()) if row[1]]
    print("//! Generated by `rust/parity/sql_tables.py`; do not edit.")
    print()
    print("/// Function names (sorted) with argument-count bit masks (0-4) per parser")
    print("/// dialect (base, postgres, mysql, sqlite, tsql, duckdb, athena).")
    print(f"pub(super) const FUNCTIONS: [(&str, [u8; 7]); {len(rows)}] = [")
    for name, row in rows:
        print(f'    ("{name}", {row}),')
    print("];")
    print()
    print("/// Type names (sorted, upper case) that Python verifies in a CAST, with a")
    print("/// bit per parser dialect in the order above.")
    print(f"pub(super) const TYPES: [(&str, u8); {len(types)}] = [")
    for name, mask in types:
        print(f'    ("{name}", {mask}),')
    print("];")


if __name__ == "__main__":
    main()
