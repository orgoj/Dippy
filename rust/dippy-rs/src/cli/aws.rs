    fn ctx_with_raw<'a>(tokens: &[&str], raw: &[&str], exp: &[bool]) -> HandlerContext<'a> {
        let mut ctx = HandlerContext::new(tokens);
        ctx.raw_words = raw.iter().map(|s| s.to_string()).collect();
        ctx.word_has_expansions = exp.to_vec();
        ctx
    }

    #[test]
    fn athena_query_string_extraction() {
        let ctx = ctx_with_raw(
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "SELECT 1",
            ],
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "'SELECT 1'",
            ],
            &[false; 5],
        );
        assert_eq!(
            extract_athena_query_string(&ctx).as_deref(),
            Some("SELECT 1")
        );

        let ctx = ctx_with_raw(
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string=SELECT 1",
            ],
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string='SELECT 1'",
            ],
            &[false; 4],
        );
        assert_eq!(
            extract_athena_query_string(&ctx).as_deref(),
            Some("SELECT 1")
        );

        // Expansion: uncertain
        let ctx = ctx_with_raw(
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "$Q",
            ],
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "$Q",
            ],
            &[false, false, false, false, true],
        );
        assert_eq!(extract_athena_query_string(&ctx), None);

        // No raw words: uncertain
        let ctx = HandlerContext::new(&[
            "aws",
            "athena",
            "start-query-execution",
            "--query-string",
            "SELECT 1",
        ]);
        assert_eq!(extract_athena_query_string(&ctx), None);
    }

    #[test]
    fn athena_never_allows_without_sql_analysis() {
        let ctx = ctx_with_raw(
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "SELECT 1",
            ],
            &[
                "aws",
                "athena",
                "start-query-execution",
                "--query-string",
                "'SELECT 1'",
            ],
            &[false; 5],
        );
        let r = classify(&ctx);
        if is_readonly_sql("SELECT 1", &ReadonlyOptions::default()).is_none() {
            assert_eq!(r.action.as_str(), "ask");
            assert_eq!(
                r.description.as_deref(),
                Some("aws athena start-query-execution")
            );
        }
    }

