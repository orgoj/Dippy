/// Global options that consume the next token.
const GLOBAL_OPTS_WITH_VALUE: &[&str] = &[
    "--region",
    "--profile",
    "--output",
    "--endpoint-url",
    "--cli-connect-timeout",
    "--cli-read-timeout",
    "--ca-bundle",
    "--color",
    "--query",
];

/// Find the service and action, skipping global options (shared loop of
/// Python `get_description` and `classify`).
fn service_and_action(tokens: &[String]) -> (Option<&str>, Option<&str>) {
    let mut service: Option<&str> = None;
    let mut action: Option<&str> = None;
    let mut i = 1;
    while i < tokens.len() {
        let token = tokens[i].as_str();
        if token.starts_with("--") {
            if GLOBAL_OPTS_WITH_VALUE.contains(&token) {
                i += 2;
                continue;
            }
            i += 1;
            continue;
        }
        if service.is_none() {
            service = Some(token);
            i += 1;
            continue;
        }
        if action.is_none() {
            action = Some(token);
            break;
        }
        i += 1;
    }
    (service, action)
}

/// Compute description for aws command.
pub fn get_description(tokens: &[String]) -> String {
    if tokens.len() < 2 {
        return "aws".to_string();
    }
    let (service, action) = service_and_action(tokens);
    match (service, action) {
        (Some(s), Some(a)) if !s.is_empty() && !a.is_empty() => format!("aws {s} {a}"),
        (Some(s), _) if !s.is_empty() => format!("aws {s}"),
        _ => "aws".to_string(),
    }
}

/// Classify AWS CLI command.
pub fn classify(ctx: &HandlerContext) -> Classification {
    let tokens = &ctx.tokens;
    let base = tokens.first().map_or("aws", String::as_str);
    if tokens.len() < 2 {
        return Classification::ask_desc(base);
    }

    let desc = get_description(tokens);

    // Check for --help anywhere (makes command safe)
    if tokens.iter().any(|t| t == "--help" || t == "-h") {
        return Classification::allow_desc(desc);
    }

    // Find the service and action
    let (service, action) = service_and_action(tokens);

    let service = match service {
        Some(s) if !s.is_empty() => s,
        _ => return Classification::ask_desc(desc),
    };

    // Help is always safe
    if service == "help" || action == Some("help") {
        return Classification::allow_desc(desc);
    }

    // Always-safe services
    if ALWAYS_SAFE_SERVICES.contains(&service) {
        return Classification::allow_desc(desc);
    }

    // STS special handling
    if service == "sts" {
        if action.is_some_and(|a| STS_SAFE_ACTIONS.contains(&a)) {
            return Classification::allow_desc(desc);
        }
        return Classification::ask_desc(desc);
    }

    // Configure special handling
    if service == "configure" {
        if matches!(action, Some("list" | "list-profiles" | "get")) {
            return Classification::allow_desc(desc);
        }
        return Classification::ask_desc(desc);
    }

    // SSM special handling - --with-decryption exposes sensitive data
    if service == "ssm" && tokens.iter().any(|t| t == "--with-decryption") {
        return Classification::ask_desc(desc);
    }

    // Athena special handling - analyze SQL for read-only queries
    if service == "athena" && action == Some("start-query-execution") {
        if let Some(query_string) = extract_athena_query_string(ctx) {
            let opts = ReadonlyOptions {
                extra_write: ATHENA_WRITE.iter().map(|s| s.to_string()).collect(),
                // Python default
                bracket_identifiers: true,
                dialect: Some("athena".to_string()),
                ..ReadonlyOptions::default()
            };
            match is_readonly_sql(&query_string, &opts) {
                Some(true) => return Classification::allow_desc(format!("{desc} (read-only)")),
                Some(false) => return Classification::ask_desc(format!("{desc} (write)")),
                None => {}
            }
        }
        // Couldn't determine - ask
        return Classification::ask_desc(desc);
    }

    let action = match action {
        Some(a) if !a.is_empty() => a,
        // Default: ask user
        _ => return Classification::ask_desc(desc),
    };

    // Check specific safe commands
    if SAFE_COMMANDS.contains(&(service, action)) {
        return Classification::allow_desc(desc);
    }

    // Check action patterns
    // Check exceptions first (things that look safe but aren't)
    if UNSAFE_EXCEPTIONS.contains(&action) {
        return Classification::ask_desc(desc);
    }

    // Exact safe actions
    if SAFE_ACTIONS_EXACT.contains(&action) {
        return Classification::allow_desc(desc);
    }

    // Safe prefixes
    if SAFE_ACTION_PREFIXES.iter().any(|p| action.starts_with(p)) {
        return Classification::allow_desc(desc);
    }

    // Unsafe keywords
    if UNSAFE_ACTION_KEYWORDS.iter().any(|k| action.contains(k)) {
        return Classification::ask_desc(desc);
    }

    // Default: ask user
    Classification::ask_desc(desc)
}

