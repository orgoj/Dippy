    #[test]
    fn matches_python_handler() {
        for (tokens, raw, exp, action, desc) in PY_CASES {
            let mut ctx = HandlerContext::new(tokens);
            ctx.raw_words = raw.iter().map(|s| s.to_string()).collect();
            ctx.word_has_expansions = exp.to_vec();
            let result = classify(&ctx);
            // Python decided through SQL analysis: until `crate::sql` is
            // ported (it answers "unknown"), Rust must ask without a suffix.
            let sql_desc = desc.and_then(|d| {
                d.strip_suffix(" (read-only)")
                    .or_else(|| d.strip_suffix(" (write)"))
            });
            if let Some(stripped) = sql_desc
                && is_readonly_sql("SELECT 1", &ReadonlyOptions::default()).is_none()
            {
                assert_eq!(result.action.as_str(), "ask", "{tokens:?}");
                assert_eq!(result.description.as_deref(), Some(stripped), "{tokens:?}");
                continue;
            }
            assert_eq!(result.action.as_str(), *action, "{tokens:?}");
            assert_eq!(result.description.as_deref(), *desc, "{tokens:?}");
        }
    }
