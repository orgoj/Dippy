/// `dippy.cli.sql_args.literal_sql_arg`: the SQL Bash passes for a literal
/// word, or `None` if uncertain.
fn literal_sql_arg(ctx: &HandlerContext, index: usize, prefix: &str) -> Option<String> {
    if index >= ctx.tokens.len() || ctx.raw_words.len() != ctx.tokens.len() {
        return None;
    }
    if ctx.word_has_expansions.get(index).copied().unwrap_or(false) {
        return None;
    }
    let mut raw = ctx.raw_words[index].as_str();
    if !prefix.is_empty() {
        raw = raw.strip_prefix(prefix)?;
    }
    decode_literal_word(raw, false)
}

/// Extract `--query-string` value from Athena command tokens.
fn extract_athena_query_string(ctx: &HandlerContext) -> Option<String> {
    let tokens = &ctx.tokens;
    for (i, token) in tokens.iter().enumerate() {
        if token == "--query-string" && i + 1 < tokens.len() {
            return literal_sql_arg(ctx, i + 1, "");
        }
        if token.starts_with("--query-string=") {
            return literal_sql_arg(ctx, i, "--query-string=");
        }
    }
    None
}

