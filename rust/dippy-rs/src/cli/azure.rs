/// Compute description for az command.
pub fn get_description(tokens: &[String]) -> String {
    if tokens.len() < 2 {
        return "az".to_string();
    }
    let parts = extract_parts(&tokens[1..]);
    if parts.is_empty() {
        return "az".to_string();
    }
    format!("az {}", parts[..parts.len().min(3)].join(" "))
}

/// Classify az command.
pub fn classify(ctx: &HandlerContext) -> Classification {
    let tokens = &ctx.tokens;
    let base = tokens.first().map_or("az", String::as_str);
    if tokens.len() < 2 {
        return Classification::ask_desc(base);
    }

    let parts = extract_parts(&tokens[1..]);
    if parts.is_empty() {
        return Classification::ask_desc(base);
    }

    let desc = get_description(tokens);

    // Help is always safe
    if parts.contains(&"help") || tokens.iter().any(|t| t == "-h" || t == "--help") {
        return Classification::allow_desc(desc);
    }

    // Check first part for unsafe groups
    if UNSAFE_GROUPS.contains(&parts[0]) {
        return Classification::ask_desc(desc);
    }

    // Check first part for safe groups
    if SAFE_GROUPS.contains(&parts[0]) {
        return Classification::allow_desc(desc);
    }

    // Handle account specially
    if parts[0] == "account" {
        if parts.len() > 1 {
            if ACCOUNT_SAFE_COMMANDS.contains(&parts[1]) {
                return Classification::allow_desc(desc);
            }
            if ACCOUNT_UNSAFE_COMMANDS.contains(&parts[1]) {
                return Classification::ask_desc(desc);
            }
        }
        return Classification::allow_desc(desc);
    }

    // Handle devops configure --list
    if parts[0] == "devops" && parts.len() > 1 && parts[1] == "configure" {
        if tokens.iter().any(|t| t == "--list") {
            return Classification::allow_desc(desc);
        }
        return Classification::ask_desc(desc);
    }

    // Check commands with safe subcommands (e.g., az bicep version)
    if let Some(safe) = safe_subcommands(parts[0])
        && parts.len() > 1
        && safe.contains(&parts[1])
    {
        return Classification::allow_desc(desc);
    }

    // Check unsafe keywords FIRST (they take precedence)
    for part in &parts {
        if UNSAFE_ACTION_KEYWORDS.contains(part) {
            return Classification::ask_desc(desc);
        }
        if UNSAFE_EXCEPTIONS.contains(part) {
            return Classification::ask_desc(desc);
        }
        if part.starts_with("set-") {
            return Classification::ask_desc(desc);
        }
    }

    // Check if any part is a safe action keyword
    for part in &parts {
        if SAFE_ACTION_KEYWORDS.contains(part) {
            return Classification::allow_desc(desc);
        }
        if SAFE_ACTION_PREFIXES.iter().any(|p| part.starts_with(p)) {
            return Classification::allow_desc(desc);
        }
    }

    Classification::ask_desc(desc)
}

/// Extract command parts (service/subgroup/action), skipping flags and their
/// arguments.
fn extract_parts(tokens: &[String]) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut i = 0;
    while i < tokens.len() && parts.len() < 5 {
        let token = tokens[i].as_str();

        // Skip flags
        if token.starts_with('-') {
            if FLAGS_WITH_ARG.contains(&token) && i + 1 < tokens.len() {
                i += 2; // Skip flag and its argument
            } else {
                i += 1; // Flag with value like --output=json, or boolean flag
            }
            continue;
        }

        // Looks like a positional argument (has slashes, dots, or is a value)
        if token.contains('/') || token.contains('.') || token.contains('@') {
            i += 1;
            continue;
        }

        // Skip what looks like values (UUIDs, numbers, etc.)
        if looks_like_value(token) {
            i += 1;
            continue;
        }

        // This is a command part
        parts.push(token);
        i += 1;
    }

    parts
}

/// Check if token looks like a value rather than a command.
fn looks_like_value(token: &str) -> bool {
    // UUIDs
    if token.chars().count() == 36 && token.matches('-').count() == 4 {
        return true;
    }
    // Pure numbers
    if py_isdigit(token) {
        return true;
    }
    // Looks like a resource path
    token.starts_with("/subscriptions/")
}

